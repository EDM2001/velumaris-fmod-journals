// Build scripts/ornaments.mjs: the ornate-frame sprite the story pages use (P2, look A).
//
// The frame furniture and the seven arc marks are lifted from the archives'
// OrnateFrame.astro, the one source, so the two never drift. Two marks are drawn
// here because the archives do not have them yet:
//   rings — Arc 8 Eden (DM ruling 2026-09-25, round 1 card 1): open rings, each
//           mouth wider than the last, the Crown's star on the centre island.
//   gem   — the house-gold corner for NPC, place and faction pages (card 5).
//
//   node dev/story-pages/build-ornaments.js      (re-run after the archives change)
//
// dev/ is never deployed; scripts/ornaments.mjs is, and is committed.
const fs = require('fs');
const path = require('path');

const MOD = path.resolve(__dirname, '..', '..');
const ASTRO = path.resolve(MOD, '..', 'velumaris-archives', 'src', 'components', 'ui', 'OrnateFrame.astro');

const r = (n) => Math.round(n * 100) / 100;
const P = (x, y) => `${r(x)} ${r(y)}`;
const rad = (d) => (d * Math.PI) / 180;
const onCircle = (cx, cy, R, deg) => [cx + R * Math.sin(rad(deg)), cy + R * Math.cos(rad(deg))];
const sparkle = (cx, cy, R, p) =>
  `M ${P(cx, cy - R)} Q ${P(cx + p, cy - p)} ${P(cx + R, cy)} Q ${P(cx + p, cy + p)} ${P(cx, cy + R)} Q ${P(cx - p, cy + p)} ${P(cx - R, cy)} Q ${P(cx - p, cy - p)} ${P(cx, cy - R)} Z`;
const gem = (x, y, g) => `M ${P(x, y - g)} L ${P(x + g, y)} L ${P(x, y + g)} L ${P(x - g, y)} Z`;
// Every mark is authored upright (local -y points into the corner) and set on the
// diagonal the same way the archives' marks are.
const place = (inner) => `<g transform="translate(11.6 11.6) rotate(-45) scale(1.12)">${inner}</g>`;

/** Arc 8: the rings of Eden. Four open rings stand for seven (seven will not read at 44px). */
function rings() {
  const cx = 0;
  const cy = 1.2;
  // [radius, half-angle of the mouth, stroke, opacity]. The mouths face away from
  // the corner and widen outward, as the city's do (ruled 2026-08-20), so the
  // frame's diamond trail runs on out through them.
  const spec = [
    [2.35, 24, 0.85, 0.95],
    [3.75, 34, 0.9, 0.85],
    [5.15, 46, 0.9, 0.72],
    [6.55, 60, 0.85, 0.6],
  ];
  let s = '';
  for (const [R, gap, w, op] of spec) {
    const [x1, y1] = onCircle(cx, cy, R, gap);
    const [x2, y2] = onCircle(cx, cy, R, 360 - gap);
    // The outer rings break into islands: Eden is fifty islands, not solid rings.
    const dash = R > 4.5 ? ` stroke-dasharray="${r(R * 0.95)} ${r(R * 0.28)}"` : '';
    s += `<path d="M ${P(x1, y1)} A ${r(R)} ${r(R)} 0 1 0 ${P(x2, y2)}" stroke="currentColor" stroke-width="${w}" stroke-linecap="butt"${dash} fill="none" opacity="${op}"/>`;
  }
  // The two lips of the outer mouth carry a bead each: the bridgeheads.
  const [lx, ly] = onCircle(cx, cy, 6.55, 60);
  s += `<path d="${gem(lx, ly, 0.55)} ${gem(-lx, ly, 0.55)}" fill="currentColor" opacity="0.7"/>`;
  // The Crown's cold star on the centre island.
  s += `<path d="${sparkle(cx, cy, 1.55, 0.32)}" fill="currentColor" opacity="1"/>`;
  return place(s);
}

/** House gold: a cut gem with its table as a void, on the coin's cradle arc. */
function houseGem() {
  const kite = (t, w, g, b) => `M ${P(0, t)} L ${P(w, g)} L ${P(0, b)} L ${P(-w, g)} Z`;
  let s = `<path d="M -3.2 5.6 A 3.6 3.6 0 0 0 3.2 5.6" stroke="currentColor" stroke-width="0.5" fill="none" opacity="0.45"/>`;
  s += `<path d="${gem(-3.2, 5.6, 0.5)} ${gem(3.2, 5.6, 0.5)}" fill="currentColor" opacity="0.5"/>`;
  // Outer stone, a girdle-to-table void ring, and the table left solid.
  s += `<path fill-rule="evenodd" d="${kite(-5.6, 3.5, -0.9, 4.6)} ${kite(-3.9, 2.25, -0.9, 2.9)} ${kite(-2.9, 1.45, -0.9, 1.5)}" fill="currentColor" opacity="0.92"/>`;
  s += `<path d="${gem(4.6, -0.9, 0.45)} ${gem(-4.6, -0.9, 0.45)}" fill="currentColor" opacity="0.6"/>`;
  return place(s);
}

const src = fs.readFileSync(ASTRO, 'utf8');
const defs = src.split('<defs>')[1].split('</defs>')[0].replace(/\{\/\*[\s\S]*?\*\/\}/g, '');
const ids = [...defs.matchAll(/<g id="vel-of-([a-z]+)">/g)].map((m) => m[1]);
for (const need of ['frame', 'butterfly', 'nightfang', 'lifetree', 'crystal', 'celestial', 'eye', 'coin']) {
  if (!ids.includes(need)) throw new Error(`OrnateFrame.astro has no vel-of-${need} group`);
}
const opens = (defs.match(/<g\b/g) || []).length;
const closes = (defs.match(/<\/g>/g) || []).length;
if (opens !== closes) throw new Error(`unbalanced <g> in the lifted defs: ${opens} vs ${closes}`);

const sprite = (
  '<svg xmlns="http://www.w3.org/2000/svg" width="0" height="0" style="position:absolute" aria-hidden="true" focusable="false"><defs>' +
  defs.replace(/\s*\n\s*/g, ' ').replace(/\s{2,}/g, ' ').trim() +
  `<g id="vel-of-rings">${rings()}</g>` +
  `<g id="vel-of-gem">${houseGem()}</g>` +
  '</defs></svg>'
);

const out = `// GENERATED by dev/story-pages/build-ornaments.js from the archives' OrnateFrame.astro.
// Do not edit by hand: change the archives (or the two marks drawn in that script) and re-run it.

/** The frame furniture and every corner mark, as one hidden sprite the pages \`<use>\`. */
export const SPRITE = ${JSON.stringify(sprite)};

/** Arc number -> corner mark. Anything that is not a session page takes \`gem\`. */
export const MOTIF_BY_ARC = { 1: 'coin', 2: 'eye', 3: 'celestial', 4: 'crystal', 5: 'lifetree', 6: 'nightfang', 7: 'butterfly', 8: 'rings' };

/**
 * Arc colours. \`dark\` is the archives' brandColor (themes.ts); \`light\` is the
 * first stop of its badge gradient, deep enough to hold on a light page.
 */
export const ARC_COLOURS = {
  1: { dark: '#fbbf24', light: '#a86a07' },
  2: { dark: '#f472b6', light: '#be185d' },
  3: { dark: '#60a5fa', light: '#1d5fd1' },
  4: { dark: '#ef4444', light: '#b91c1c' },
  5: { dark: '#34d399', light: '#047857' },
  6: { dark: '#a78bfa', light: '#6d28d9' },
  7: { dark: '#818cf8', light: '#4338ca' },
  8: { dark: '#5b9dff', light: '#1d4fb8' },
};
`;
fs.writeFileSync(path.join(MOD, 'scripts', 'ornaments.mjs'), out);
console.log(`scripts/ornaments.mjs: ${ids.length} lifted groups + rings + gem, ${(out.length / 1024).toFixed(1)} KB`);
